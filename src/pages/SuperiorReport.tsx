import { useEffect, useState } from 'react';
import { useParams } from 'react-router-dom';
import { useProposalReport } from '@/hooks/useProposalReport';
import { ProposalOutputsComponent } from '@/components/proposal/ProposalOutputs';
import { ProposalMap } from '@/components/proposal/ProposalMap';
import { Badge } from '@/components/ui/badge';
import { AlertCircle, Loader2 } from 'lucide-react';
import { formatDistanceToNow } from 'date-fns';
import { isRedLoftWorkspace } from '@/lib/workspaceFeatures';

export default function SuperiorReport() {
  const { token } = useParams<{ token: string }>();
  const { loadReport, isLoading } = useProposalReport();
  const [report, setReport] = useState<Awaited<ReturnType<typeof loadReport>>>(null);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    if (!token) {
      setError('Invalid report link');
      return;
    }

    const load = async () => {
      const result = await loadReport(token);
      if (result) {
        setReport(result);
      } else {
        setError('Report not found or has expired');
      }
    };

    load();
  }, [token]);

  if (isLoading) {
    return (
      <div className="min-h-screen flex items-center justify-center bg-background">
        <div className="text-center">
          <Loader2 className="h-8 w-8 animate-spin mx-auto text-primary" />
          <p className="mt-4 text-muted-foreground">Loading report...</p>
        </div>
      </div>
    );
  }

  if (error || !report) {
    return (
      <div className="min-h-screen flex items-center justify-center bg-background">
        <div className="text-center">
          <AlertCircle className="h-12 w-12 mx-auto text-destructive" />
          <h1 className="mt-4 text-xl font-semibold">Report Not Found</h1>
          <p className="mt-2 text-muted-foreground">
            {error || 'This report may have expired or been deleted.'}
          </p>
        </div>
      </div>
    );
  }

  const isExpired = report.expiresAt && new Date(report.expiresAt) < new Date();

  if (isExpired) {
    return (
      <div className="min-h-screen flex items-center justify-center bg-background">
        <div className="text-center">
          <AlertCircle className="h-12 w-12 mx-auto text-warning" />
          <h1 className="mt-4 text-xl font-semibold">Report Expired</h1>
          <p className="mt-2 text-muted-foreground">
            This report link has expired and is no longer available.
          </p>
        </div>
      </div>
    );
  }

  return (
    <div className="min-h-screen bg-background">
      <div className="container py-8 max-w-4xl">
        {/* Header */}
        <div className="mb-8">
          <div className="flex items-start justify-between">
            <div>
              <h1 className="text-3xl font-bold">
                {report.communityName || 'Fitness Center Proposal'}
              </h1>
              {report.communityAddress && (
                <p className="text-lg text-muted-foreground mt-1">
                  {report.communityAddress}
                </p>
              )}
            </div>
            <Badge variant="secondary">
              Created {formatDistanceToNow(new Date(report.createdAt), { addSuffix: true })}
            </Badge>
          </div>
          {report.expiresAt && (
            <p className="mt-2 text-sm text-muted-foreground">
              Expires {formatDistanceToNow(new Date(report.expiresAt), { addSuffix: true })}
            </p>
          )}
        </div>

        {/* Outputs */}
        <div className="space-y-6">
          <ProposalOutputsComponent
            outputs={report.outputs}
            multifamilyComps={report.multifamilyComps}
            fitnessComps={report.fitnessComps}
            hasAddress={!!report.communityAddress}
            hasUnitsOrSF={!!(report.units || report.sfOverride)}
          />

          {/* Map */}
          {report.mapCenter && (
            <ProposalMap
              mapCenter={report.mapCenter}
              communityName={report.communityName}
              multifamilyComps={report.multifamilyComps}
              fitnessComps={report.fitnessComps}
            />
          )}
        </div>

        {/* Footer */}
        <div className="mt-12 pt-6 border-t text-center text-sm text-muted-foreground">
          <p>{isRedLoftWorkspace((report as any).workspaceId) ? 'Generated by Red Loft Consulting' : 'Generated by Superior Fitness Equipment'}</p>
        </div>
      </div>
    </div>
  );
}
